function requireObject(value, label) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} must be an object.`);
  }
  return value;
}

function requireArray(value, label) {
  if (!Array.isArray(value)) throw new Error(`${label} must be an array.`);
  return value;
}

function requireString(value, label) {
  const text = String(value ?? "").trim();
  if (!text) throw new Error(`${label} must be a non-empty string.`);
  return text;
}

function isInside(parentPath, candidatePath) {
  const relative = path.relative(path.resolve(parentPath), path.resolve(candidatePath));
  return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative));
}

function resolveRoots(options = {}) {
  const engineRoot = path.resolve(String(options.engineRoot ?? defaultEngineRoot));
  const targetText = String(options.targetRoot ?? "").trim();
  if (!targetText) throw new Error("An explicit targetRoot is required.");
  const targetRoot = path.resolve(targetText);
  for (const [label, root] of [["engineRoot", engineRoot], ["targetRoot", targetRoot]]) {
    if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) {
      throw new Error(`${label} must be an existing directory: ${root}`);
    }
    if (fs.lstatSync(root).isSymbolicLink()) {
      throw new Error(`${label} cannot be a symbolic link: ${root}`);
    }
  }
  const realEngineRoot = fs.realpathSync(engineRoot);
  const realTargetRoot = fs.realpathSync(targetRoot);
  if (realEngineRoot === realTargetRoot) {
    throw new Error("engineRoot and targetRoot must be distinct.");
  }
  return { engineRoot: realEngineRoot, targetRoot: realTargetRoot };
}

function safeTargetPath(targetRoot, projectPath) {
  const normalized = String(projectPath ?? "")
    .replaceAll("\\", "/")
    .replace(/^\.\//u, "")
    .trim();
  if (!normalized || path.isAbsolute(normalized) || path.win32.isAbsolute(normalized)) {
    throw new Error(`Unsafe target workspace path: ${normalized || "<empty>"}`);
  }
  const segments = normalized.split("/");
  if (segments.some((segment) => !segment || segment === "." || segment === "..")) {
    throw new Error(`Unsafe target workspace path: ${normalized}`);
  }
  const absolute = path.resolve(targetRoot, ...segments);
  if (!isInside(targetRoot, absolute)) {
    throw new Error(`Target workspace path escapes targetRoot: ${normalized}`);
  }
  let current = targetRoot;
  for (const segment of segments.slice(0, -1)) {
    current = path.join(current, segment);
    if (!fs.existsSync(current)) continue;
    if (fs.lstatSync(current).isSymbolicLink()) {
      throw new Error(`Target workspace path cannot contain symbolic links: ${normalized}`);
    }
  }
  return { normalized, absolute };
}

function stripJsonComments(text) {
  const source = String(text ?? "").replace(/^\uFEFF/u, "");
  let result = "";
  let inString = false;
  let escaped = false;
  let lineComment = false;
  let blockComment = false;
  for (let index = 0; index < source.length; index += 1) {
    const current = source[index];
    const next = source[index + 1];
    if (lineComment) {
      if (current === "\n") { lineComment = false; result += "\n"; }
      else result += " ";
      continue;
    }
    if (blockComment) {
      if (current === "*" && next === "/") { blockComment = false; result += "  "; index += 1; }
      else result += current === "\n" ? "\n" : " ";
      continue;
    }
    if (inString) {
      result += current;
      if (escaped) escaped = false;
      else if (current === "\\") escaped = true;
      else if (current === '"') inString = false;
      continue;
    }
    if (current === '"') { inString = true; result += current; continue; }
    if (current === "/" && next === "/") { lineComment = true; result += "  "; index += 1; continue; }
    if (current === "/" && next === "*") { blockComment = true; result += "  "; index += 1; continue; }
    result += current;
  }
  if (blockComment) throw new Error("JSONC contains an unterminated block comment.");
  return result;
}

function removeTrailingCommas(text) {
  let result = "";
  let inString = false;
  let escaped = false;
  for (let index = 0; index < text.length; index += 1) {
    const current = text[index];
    if (inString) {
      result += current;
      if (escaped) escaped = false;
      else if (current === "\\") escaped = true;
      else if (current === '"') inString = false;
      continue;
    }
    if (current === '"') { inString = true; result += current; continue; }
    if (current === ",") {
      let lookahead = index + 1;
      while (/\s/u.test(text[lookahead] ?? "")) lookahead += 1;
      if (text[lookahead] === "}" || text[lookahead] === "]") continue;
    }
    result += current;
  }
  return result;
}

function parseJsonc(text, label) {
  try {
    return requireObject(JSON.parse(removeTrailingCommas(stripJsonComments(text))), label);
  } catch (error) {
    throw new Error(`${label} is not valid JSONC: ${error.message}`);
  }
}

function orderKeys(value) {
  if (Array.isArray(value)) return value.map(orderKeys);
  if (!value || typeof value !== "object") return value;
  const output = {};
  for (const key of Object.keys(value).sort((left, right) => left.localeCompare(right, "en"))) {
    output[key] = orderKeys(value[key]);
  }
  return output;
}

function formatJson(value) {
  return `${JSON.stringify(orderKeys(value), null, 2)}\n`;
}

function formatTasks(value) {
  return `${tasksHeader}\n${JSON.stringify(value, null, 2)}\n`;
}

function readJsonc(targetRoot, projectPath, fallback) {
  const resolved = safeTargetPath(targetRoot, projectPath);
  return fs.existsSync(resolved.absolute)
    ? parseJsonc(fs.readFileSync(resolved.absolute, "utf8"), projectPath)
    : structuredClone(fallback);
}

function atomicWrite(targetRoot, projectPath, text) {
  const resolved = safeTargetPath(targetRoot, projectPath);
  fs.mkdirSync(path.dirname(resolved.absolute), { recursive: true });
  const temporary = path.join(
    path.dirname(resolved.absolute),
    `.${path.basename(resolved.absolute)}.${process.pid}.${Date.now()}.tmp`,
  );
  try {
    fs.writeFileSync(temporary, text, { encoding: "utf8", flag: "wx" });
    fs.renameSync(temporary, resolved.absolute);
  } catch (error) {
    if (fs.existsSync(temporary)) fs.rmSync(temporary, { force: true });
    throw new Error(`Cannot materialize ${projectPath}: ${error.message}`);
  }
}

function engineToolPath(engineRoot, projectPath) {
  const absolute = path.resolve(engineRoot, ...projectPath.split("/"));
  if (!isInside(engineRoot, absolute) || !fs.existsSync(absolute) || !fs.statSync(absolute).isFile()) {
    throw new Error(`Required ThreatForge tool is missing: ${projectPath}`);
  }
  return absolute;
}

function portableProjectPath(value) {
  return String(value).replaceAll("\\", "/");
}

function workspaceEngineRootReference({ engineRoot, targetRoot }) {
  if (!isInside(engineRoot, targetRoot)) return engineRoot;
  const relative = portableProjectPath(path.relative(targetRoot, engineRoot));
  return relative || ".";
}

function workspaceEngineToolReference(roots, projectPath) {
  engineToolPath(roots.engineRoot, projectPath);
  const engineReference = workspaceEngineRootReference(roots);
  return path.isAbsolute(engineReference) || path.win32.isAbsolute(engineReference)
    ? path.resolve(roots.engineRoot, ...projectPath.split("/"))
    : portableProjectPath(path.posix.join(engineReference, projectPath));
}

function taskPresentation() {
  return { reveal: "always", panel: "shared", clear: true, focus: true };
}

function buildManagedTasks(roots) {
  const engineReference = workspaceEngineRootReference(roots);
  const portable = !path.isAbsolute(engineReference) && !path.win32.isAbsolute(engineReference);
  const authoringRunner = workspaceEngineToolReference(
    roots,
    "tools/MR-0004/run-target-project-authoring.mjs",
  );
  const targetCheck = workspaceEngineToolReference(
    roots,
    "tools/MR-0004/run-target-project-check.mjs",
  );
  const installer = workspaceEngineToolReference(
    roots,
    "tools/MR-0002/install-vscode-governed-markdown-assistance.mjs",
  );
  const authoringTask = (mode) => ({
    label: mode === "preview"
      ? targetProjectWorkspaceTaskLabels.preview
      : targetProjectWorkspaceTaskLabels.create,
    type: "process",
    command: "node",
    args: [
      authoringRunner,
      mode === "preview" ? "--preview" : "--create",
      "--engine-root",
      engineReference,
      "--target-root",
      "${workspaceFolder}",
      "--request",
      "${relativeFile}",
    ],
    options: { cwd: "${workspaceFolder}" },
    problemMatcher: [],
    presentation: taskPresentation(),
  });
  return [
    authoringTask("preview"),
    authoringTask("create"),
    {
      label: targetProjectWorkspaceTaskLabels.validate,
      type: "process",
      command: "node",
      args: [targetCheck, "--target-root", "${workspaceFolder}"],
      options: { cwd: "${workspaceFolder}" },
      problemMatcher: [],
      presentation: taskPresentation(),
    },
    {
      label: targetProjectWorkspaceTaskLabels.installAssistance,
      type: "process",
      command: "node",
      args: [installer, "--install"],
      options: { cwd: portable ? "${workspaceFolder}" : roots.engineRoot },
      problemMatcher: [],
      presentation: taskPresentation(),
    },
  ];
}

function mergeTasks(existing, roots) {
  const tasks = existing.tasks === undefined ? [] : requireArray(existing.tasks, "tasks.tasks");
  const preserved = tasks.filter((value, index) => {
    const task = requireObject(value, `tasks.tasks[${index}]`);
    return !managedTaskLabels.has(requireString(task.label, `tasks.tasks[${index}].label`));
  });
  return {
    ...existing,
    version: existing.version ?? "2.0.0",
    tasks: [...preserved, ...buildManagedTasks(roots)],
  };
}

function mergeSettings(existing, engineReference) {
  const schemas = existing["yaml.schemas"] === undefined
    ? {}
    : requireObject(
      existing["yaml.schemas"],
      "settings.yaml.schemas",
    );

  return mergeCommonAnalysisFindingEditorRouting({
    ...existing,
    "threatforge.engineRoot": engineReference,
    "yaml.schemas": {
      ...schemas,
      [schemaAssociationKey]: [requestGlob],
    },
  });
}

function mergeExtensions(existing) {
  const recommendations = existing.recommendations === undefined
    ? []
    : requireArray(existing.recommendations, "extensions.recommendations")
      .map((value) => requireString(value, "extension recommendation"));
  const preserved = recommendations.filter(
    (value) => value !== obsoleteTargetAssistanceExtensionId,
  );
  return {
    ...existing,
    recommendations: [...new Set([
      ...preserved,
      yamlExtensionId,
      unifiedAssistanceExtensionId,
    ])].sort(),
  };
}

function expectedWorkspaceProjection(roots) {
  const commonFindingRouting =
    buildCommonAnalysisFindingEditorRoutingProjection();
  const catalog = loadTargetProjectAuthoringCatalog(roots);
  const referenceService = createSecurityRequirementAuthoringReferenceService({
    rootDir: roots.targetRoot,
    resolverRootDir: roots.engineRoot,
  });
  const schemaProviders = resolveSecurityRequirementAuthoringSchemaProviders({
    catalog,
    providers: governedDocumentAuthoringSchemaProviders,
    referenceService,
  });
  const schema = buildGovernedDocumentAuthoringSchema(catalog, {
    providers: schemaProviders,
  });
  schema.title = "ThreatForge Target Project governed document authoring request";
  schema.description =
    "Target-local request whose document rules come from ThreatForge and whose ownership candidates come from the opened Target Project.";
  schema["x-threatforge"] = {
    ...requireObject(schema["x-threatforge"], "schema.x-threatforge"),
    implemented_requirement_id: targetProjectWorkspaceRequirementId,
    ownership_scope: "target_project",
  };

  const engineReference = workspaceEngineRootReference(roots);
  const settings = mergeSettings(
    readJsonc(roots.targetRoot, settingsProjectPath, {}),
    engineReference,
  );
  const extensions = mergeExtensions(
    readJsonc(roots.targetRoot, extensionsProjectPath, { recommendations: [] }),
  );
  const tasks = mergeTasks(
    readJsonc(roots.targetRoot, tasksProjectPath, { version: "2.0.0", tasks: [] }),
    roots,
  );
  return {
    [schemaProjectPath]: formatJson(schema),
    [commonFindingRouting.schemaProjectPath]:
      commonFindingRouting.schemaText,
    [settingsProjectPath]: formatJson(settings),
    [extensionsProjectPath]: formatJson(extensions),
    [tasksProjectPath]: formatTasks(tasks),
  };
}

function assertProjectionCurrent(targetRoot, projection) {
  for (const [projectPath, expected] of Object.entries(projection)) {
    const resolved = safeTargetPath(targetRoot, projectPath);
    if (!fs.existsSync(resolved.absolute) || !fs.statSync(resolved.absolute).isFile()) {
      throw new Error(`Target Project VS Code projection is missing: ${projectPath}`);
    }
    const actual = fs.readFileSync(resolved.absolute, "utf8").replace(/^\uFEFF/u, "");
    if (actual !== expected) {
      throw new Error(`Target Project VS Code projection is stale: ${projectPath}`);
    }
  }
}

/** Materializes or checks one deterministic target-local VS Code workspace. */
export function materializeTargetProjectVsCodeWorkspace(options = {}) {
  const mode = String(options.mode ?? "");
  if (mode !== "write" && mode !== "check") {
    throw new Error("mode must be write or check.");
  }
  const roots = resolveRoots(options);
  const commonFindingRouting =
    buildCommonAnalysisFindingEditorRoutingProjection();
  const projection = expectedWorkspaceProjection(roots);
  if (mode === "write") {
    for (const [projectPath, text] of Object.entries(projection)) {
      atomicWrite(roots.targetRoot, projectPath, text);
    }
  }
  assertProjectionCurrent(roots.targetRoot, projection);
  return {
    requirementId: targetProjectWorkspaceRequirementId,
    mode,
    engineRoot: roots.engineRoot,
    engineReference: workspaceEngineRootReference(roots),
    targetRoot: roots.targetRoot,
    files: Object.keys(projection).sort(),
    taskLabels: { ...targetProjectWorkspaceTaskLabels },
    schema: schemaAssociationKey,
    requestGlob,
    commonFindingSchema:
      commonFindingRouting.schemaAssociationKey,
    commonFindingGlob:
      commonFindingRouting.fileGlob,
    recommendedExtensions: [yamlExtensionId, unifiedAssistanceExtensionId],
  };
}

function parseArgs(args) {
  let mode = null;
  let targetRoot = "";
  let engineRoot = defaultEngineRoot;
  if (args.length === 1 && (args[0] === "--help" || args[0] === "-h")) {
    return { mode: "help" };
  }
  for (let index = 0; index < args.length; index += 1) {
    const argument = String(args[index]);
    if (argument === "--write" || argument === "--check") {
      if (mode) throw new Error("Exactly one mode is required: --write or --check.");
      mode = argument.slice(2);
      continue;
    }
    if (argument !== "--target-root" && argument !== "--engine-root") {
      throw new Error(`Unsupported Target Project workspace option: ${argument}`);
    }
    const value = String(args[index + 1] ?? "").trim();
    if (!value || value.startsWith("--")) {
      throw new Error(`${argument} requires a non-empty value.`);
    }
    if (argument === "--target-root") targetRoot = value;
    else engineRoot = value;
    index += 1;
  }
  if (!mode) throw new Error("Exactly one mode is required: --write or --check.");
  if (!targetRoot) throw new Error("--target-root is required.");
  return { mode, targetRoot, engineRoot };
}

function usage() {
  return [
    "Usage:",
    "  node tools/MR-0004/materialize-target-project-vscode-workspace.mjs --write --target-root <path> [--engine-root <path>]",
    "  node tools/MR-0004/materialize-target-project-vscode-workspace.mjs --check --target-root <path> [--engine-root <path>]",
  ].join("\n");
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.mode === "help") {
    console.log(usage());
    return;
  }
  const result = materializeTargetProjectVsCodeWorkspace(options);
  console.log("Target Project VS Code workspace materialization succeeded.");
  console.log(`Implemented requirement: ${result.requirementId}`);
  console.log(`Mode: ${result.mode}`);
  console.log(`Target root: ${result.targetRoot}`);
  console.log(`Files: ${result.files.length}`);
  console.log(`Preview task: ${result.taskLabels.preview}`);
  console.log(`Create task: ${result.taskLabels.create}`);
  console.log(`Validation task: ${result.taskLabels.validate}`);
  console.log(`Markdown assistance task: ${result.taskLabels.installAssistance}`);
  console.log(`Schema: ${result.schema}`);
  console.log(`Common Finding schema: ${result.commonFindingSchema}`);
  console.log(`Common Finding glob: ${result.commonFindingGlob}`);
}

const directExecutionUrl = process.argv[1]
  ? pathToFileURL(path.resolve(process.argv[1])).href
  : "";
if (import.meta.url === directExecutionUrl) {
  try {
    main();
  } catch (error) {
    console.error(`Target Project VS Code workspace materialization failed: ${error.message}`);
    console.error(`\n${usage()}`);
    process.exitCode = 1;
  }
}
